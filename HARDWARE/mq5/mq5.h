/**
  ******************************************************************************
  * @file    mq5.h
  * @brief   MQ-5 气体传感器驱动（模拟量输出，PB0 = ADC1_IN8）
  * @note    - 模拟量输出直接反映气体浓度高低（数字越高浓度越大）
  *          - 上电预热约 1 分钟数值才稳定；初版输出 0~100 等级便于云端使用
  ******************************************************************************
  */
#ifndef __MQ5_H
#define __MQ5_H

#include <stdint.h>

/**
  * @brief  读取 MQ-5 气体浓度等级（0~100）
  * @note   内部按 ADC 原始值(0~4095)线性映射到 0~100；
  *         后续如需真实 ppm，需按手册曲线标定
  */
uint16_t MQ5_ReadLevel(void);

/**
  * @brief  读取 MQ-5 原始 ADC 值（0~4095）
  */
uint16_t MQ5_ReadRaw(void);

#endif /* __MQ5_H */
